import { Database, Download, FileCheck } from 'lucide-react';
import { useLiveQuery } from 'dexie-react-hooks';
import { db } from '../lib/db';

export default function DataExportPage() {
  const lotCount = useLiveQuery(() => db.lots.count());
  const recyclerCount = useLiveQuery(() => db.recyclers.count());

  const downloadCSV = (filename: string, csvContent: string) => {
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement('a');
    const url = URL.createObjectURL(blob);
    link.setAttribute('href', url);
    link.setAttribute('download', filename);
    link.style.visibility = 'hidden';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const exportTransactions = async () => {
    const lots = await db.lots.toArray();
    let csv = 'lot_id,material,weight_kg,estimated_value_inr,status,timestamp\n';
    lots.forEach(lot => {
      csv += `${lot.id},${lot.material},${lot.weight},${lot.estimate},${lot.status},${new Date(lot.timestamp).toISOString()}\n`;
    });
    downloadCSV('transactions_dataset.csv', csv);
  };

  const exportRecyclers = async () => {
    const recyclers = await db.recyclers.toArray();
    let csv = 'recycler_id,name,offered_rate_per_kg,distance_km,is_verified\n';
    recyclers.forEach(r => {
      csv += `${r.id},${r.name},${r.rate},${r.distance},${r.verified}\n`;
    });
    downloadCSV('recyclers_dataset.csv', csv);
  };

  const generateEPRCertificate = async () => {
    const completedLots = await db.lots.where('status').equals('COMPLETED').toArray();
    const totalWeight = completedLots.reduce((acc, lot) => acc + parseFloat(lot.weight), 0).toFixed(2);
    
    const certWindow = window.open('', '_blank');
    if (certWindow) {
      certWindow.document.write(`
        <html>
          <head>
            <title>EPR Compliance Certificate</title>
            <style>
              body { font-family: 'Helvetica Neue', Helvetica, Arial, sans-serif; padding: 40px; background: #f4f4f4; }
              .certificate { background: white; padding: 40px; border-radius: 10px; max-width: 800px; margin: auto; box-shadow: 0 4px 15px rgba(0,0,0,0.1); border: 4px solid #14213D; }
              .header { text-align: center; border-bottom: 2px solid #eee; padding-bottom: 20px; margin-bottom: 20px; }
              .title { font-size: 28px; font-weight: bold; color: #14213D; margin: 0; }
              .subtitle { font-size: 16px; color: #666; margin-top: 5px; }
              .content { font-size: 18px; line-height: 1.6; color: #333; }
              .highlight { font-weight: bold; color: #2E7D32; }
              .footer { margin-top: 40px; border-top: 2px solid #eee; padding-top: 20px; display: flex; justify-content: space-between; align-items: center; }
              .stamp { color: #d32f2f; border: 2px solid #d32f2f; padding: 10px; font-weight: bold; transform: rotate(-10deg); display: inline-block; font-size: 20px; letter-spacing: 2px; }
            </style>
          </head>
          <body>
            <div class="certificate">
              <div class="header">
                <h1 class="title">EPR Compliance Certificate</h1>
                <p class="subtitle">Generated by Kabadiwala Connect Platform</p>
              </div>
              <div class="content">
                <p>This is to certify that <strong>Kabadiwala Connect</strong> has successfully facilitated the formal collection and handover of E-Waste to CPCB-authorized recycling facilities.</p>
                <p><strong>Certificate ID:</strong> EPR-${crypto.randomUUID().split('-')[0].toUpperCase()}</p>
                <p><strong>Date of Issue:</strong> ${new Date().toLocaleDateString()}</p>
                <br/>
                <p>Total Material Processed & Verified:</p>
                <h2><span class="highlight">${totalWeight} KG</span> of Electronic Waste</h2>
                <br/>
                <p>All associated transactions have been digitally verified using the Kabadiwala Connect Handover Hash protocol, ensuring 100% traceability from the informal collector to the formal recycler.</p>
              </div>
              <div class="footer">
                <div>
                  <p><strong>Authorized Signatory</strong></p>
                  <p>Kabadiwala Connect System</p>
                </div>
                <div class="stamp">VERIFIED & TRACEABLE</div>
              </div>
            </div>
            <script>
               setTimeout(() => { window.print(); }, 500);
            </script>
          </body>
        </html>
      `);
      certWindow.document.close();
    }
  };

  return (
    <div className="p-6 bg-[#14213D] min-h-screen text-white pb-24">
      <h1 className="text-2xl font-bold mb-2 flex items-center"><Database className="mr-2" /> Data Intelligence</h1>
      <p className="text-gray-400 mb-8">Living datasets generated continuously through platform usage.</p>

      <div className="grid grid-cols-2 gap-4 mb-8">
        <div className="bg-white text-black p-4 rounded-xl shadow-lg border-l-4 border-[#FFC72C]">
          <p className="text-sm text-gray-500 font-bold uppercase">Digital Lots</p>
          <p className="text-3xl font-black">{lotCount ?? 0}</p>
        </div>
        <div className="bg-white text-black p-4 rounded-xl shadow-lg border-l-4 border-[#FFC72C]">
          <p className="text-sm text-gray-500 font-bold uppercase">Recyclers</p>
          <p className="text-3xl font-black">{recyclerCount ?? 0}</p>
        </div>
      </div>

      <h2 className="font-bold mb-4">Regulatory Compliance</h2>
      <div className="mb-8">
        <button 
          onClick={generateEPRCertificate}
          className="w-full bg-green-600 hover:bg-green-700 text-white p-4 rounded-xl flex items-center justify-center font-bold shadow-lg transition-colors"
        >
          <FileCheck className="mr-2" />
          Generate EPR Certificate
        </button>
        <p className="text-xs text-gray-400 mt-2 text-center">Generates a traceable compliance certificate for brands.</p>
      </div>

      <h2 className="font-bold mb-4">Export Datasets (CSV)</h2>
      
      <div className="space-y-3">
        <div className="bg-gray-800 p-4 rounded-xl flex justify-between items-center border border-gray-700">
          <span className="font-medium text-sm">Transactions_Dataset.csv</span>
          <button onClick={exportTransactions} className="text-blue-400 hover:text-blue-300 p-2 bg-gray-700 rounded-lg">
            <Download size={18} />
          </button>
        </div>
        <div className="bg-gray-800 p-4 rounded-xl flex justify-between items-center border border-gray-700">
          <span className="font-medium text-sm">Recycler_Capabilities.csv</span>
          <button onClick={exportRecyclers} className="text-blue-400 hover:text-blue-300 p-2 bg-gray-700 rounded-lg">
            <Download size={18} />
          </button>
        </div>
      </div>
      
      <div className="mt-8 text-xs text-gray-500 text-center">
        Data is synced automatically when internet connectivity is restored via Supabase.
      </div>
    </div>
  );
}
